#!/usr/bin/env node
/**
 * Generate deploy/jitsi/.env for local self-hosted Jitsi (meet.localhost).
 * Syncs JWT_APP_ID / JWT_APP_SECRET with Izara meeting-server (.env.docker).
 *
 * Usage: node scripts/jitsi/setup-local-jitsi.mjs [--sync-docker-env] [--lan]
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '../..');
const jitsiDir = path.join(repoRoot, 'deploy/jitsi');
const vendorDir = path.join(jitsiDir, 'docker-jitsi-meet');
const envPath = path.join(jitsiDir, '.env');
const dockerEnvPath = path.join(repoRoot, '.env.docker');

function readKeyFromDockerEnv(key) {
  if (!fs.existsSync(dockerEnvPath)) return '';
  const text = fs.readFileSync(dockerEnvPath, 'utf8');
  for (const line of text.split('\n')) {
    const m = line.match(new RegExp(`^${key}=(.*)$`));
    if (m) return m[1].trim();
  }
  return '';
}

function randomHex(bytes = 32) {
  return crypto.randomBytes(bytes).toString('hex');
}

function ensureVendor() {
  if (!fs.existsSync(path.join(vendorDir, 'docker-compose.yml'))) {
    console.error(
      'Missing deploy/jitsi/docker-jitsi-meet — run:\n' +
        '  git clone --depth 1 https://github.com/jitsi/docker-jitsi-meet.git deploy/jitsi/docker-jitsi-meet',
    );
    process.exit(1);
  }
}

function main() {
  ensureVendor();
  fs.mkdirSync(path.join(jitsiDir, 'config'), { recursive: true });

  const syncDocker = process.argv.includes('--sync-docker-env');
  const isLan = process.argv.includes('--lan');
  const lanIp = process.env.LAN_SERVER_IP || '192.168.0.1'; // NOSONAR S1313 — override via LAN_SERVER_IP on Ubuntu LAN
  const publicUrl = isLan ? 'https://meet.demotoday.net' : 'https://meet.localhost:8443';
  const jitsiDomain = isLan ? 'meet.demotoday.net' : 'meet.localhost:8443';
  const appId = readKeyFromDockerEnv('JITSI_APP_ID') || 'izara-telemedicine';
  let jwtSecret = readKeyFromDockerEnv('JITSI_JWT_SECRET');
  if (!jwtSecret) jwtSecret = randomHex(32);

  const readExistingJitsiEnv = (key) => {
    if (!fs.existsSync(envPath)) return '';
    const text = fs.readFileSync(envPath, 'utf8');
    for (const line of text.split('\n')) {
      const m = line.match(new RegExp(`^${key}=(.*)$`));
      if (m) return m[1].trim();
    }
    return '';
  };
  const componentPassword = (key) => readExistingJitsiEnv(key) || randomHex(16);

  const envLines = [
    '# Generated by scripts/jitsi/setup-local-jitsi.mjs — do not commit secrets',
    `CONFIG=${path.join(jitsiDir, 'config').replaceAll('\\', '/')}`,
    `PUBLIC_URL=${publicUrl}`,
    'HTTP_PORT=8000',
    'HTTPS_PORT=8443',
    'TZ=Asia/Bangkok',
    'RESTART_POLICY=unless-stopped',
    'JITSI_IMAGE_VERSION=stable-9646',
    '',
    '# JWT (must match Izara meeting-server JITSI_APP_ID / JITSI_JWT_SECRET)',
    'ENABLE_AUTH=1',
    'AUTH_TYPE=jwt',
    `JWT_APP_ID=${appId}`,
    `JWT_APP_SECRET=${jwtSecret}`,
    'JWT_ACCEPTED_ISSUERS=izara-telemedicine',
    'JWT_ACCEPTED_AUDIENCES=jitsi',
    'JWT_ASAP_KEYSERVER=',
    'JWT_ALLOW_EMPTY=0',
    'JWT_AUTH_TYPE=token',
    'ENABLE_GUESTS=1',
    '',
    '# Izara branding',
    'DEFAULT_LANGUAGE=th',
    'ENABLE_WELCOME_PAGE=0',
    'ENABLE_LOBBY=0',
    '',
    isLan ? `# Ubuntu LAN — advertise JVB on ${lanIp}` : '# Local dev — single bridge',
    `JVB_ADVERTISE_IPS=${isLan ? lanIp : '127.0.0.1'}`,
    `DOCKER_HOST_ADDRESS=${isLan ? lanIp : '127.0.0.1'}`,
    '',
    '# WebSocket media (required when TLS terminates at nginx → Jitsi :8000)',
    'ENABLE_COLIBRI_WEBSOCKET=1',
    'ENABLE_XMPP_WEBSOCKET=1',
    'JVB_ADVERTISE_PRIVATE_CANDIDATES=true',
    '',
    '# Disable unused services for local dev',
    'ENABLE_RECORDING=0',
    'ENABLE_TRANSCRIPTIONS=0',
    '',
    '# XMPP component passwords (docker-jitsi-meet required)',
    `JICOFO_AUTH_PASSWORD=${componentPassword('JICOFO_AUTH_PASSWORD')}`,
    `JVB_AUTH_PASSWORD=${componentPassword('JVB_AUTH_PASSWORD')}`,
    `JIGASI_XMPP_PASSWORD=${componentPassword('JIGASI_XMPP_PASSWORD')}`,
    `JIBRI_RECORDER_PASSWORD=${componentPassword('JIBRI_RECORDER_PASSWORD')}`,
    `JIBRI_XMPP_PASSWORD=${componentPassword('JIBRI_XMPP_PASSWORD')}`,
  ];

  fs.writeFileSync(envPath, envLines.join('\n') + '\n', 'utf8');
  console.log(`✅ Wrote ${envPath}`);

  if (syncDocker && fs.existsSync(dockerEnvPath)) {
    let dockerText = fs.readFileSync(dockerEnvPath, 'utf8');
    const upsert = (key, value) => {
      const re = new RegExp(`^${key}=.*$`, 'm');
      const line = `${key}=${value}`;
      dockerText = re.test(dockerText)
        ? dockerText.replace(re, line)
        : `${dockerText.trimEnd()}\n${line}\n`;
    };
    upsert('JITSI_DOMAIN', jitsiDomain);
    upsert('VITE_JITSI_DOMAIN', jitsiDomain);
    upsert('JITSI_APP_ID', appId);
    upsert('JITSI_JWT_SECRET', jwtSecret);
    fs.writeFileSync(dockerEnvPath, dockerText, 'utf8');
    console.log(`✅ Synced JWT + JITSI_DOMAIN into ${dockerEnvPath}`);
  } else {
    console.log('\nAdd to .env.docker (or re-run with --sync-docker-env):');
    console.log(`  JITSI_DOMAIN=${jitsiDomain}`);
    console.log(`  JITSI_JWT_SECRET=${jwtSecret}`);
    console.log(`  JITSI_APP_ID=${appId}`);
  }

  if (isLan) {
    console.log('\nNext (Ubuntu LAN):');
    console.log('  1. Add meet.demotoday.net to Windows hosts + mkcert CA');
    console.log('  2. docker compose --env-file .env.docker -f docker-compose.yml -f deploy/jitsi/docker-compose.jitsi.yml --profile full --profile jitsi up -d --build');
    console.log('  3. curl -sk https://meet.demotoday.net/about/health');
  } else {
    console.log('\nNext:');
    console.log(String.raw`  1. Add to C:\Windows\System32\drivers\etc\hosts: 127.0.0.1 meet.localhost`);
    console.log('  2. docker compose --env-file .env.docker --profile full --profile jitsi up -d --build');
    console.log('  3. curl -k https://meet.localhost:8443/about/health');
  }
}

main();
